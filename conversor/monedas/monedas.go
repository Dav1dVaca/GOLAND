package monedas

func DolarAEuro(dolares float64) float64 {
	return dolares * 0.85
}

func DolarALibra(dolares float64) float64 {
	return dolares * 0.74
}

func DolarAWon(dolares float64) float64 {
	return dolares * 1350
}

func DolarABTC(dolares float64) float64 {
	return dolares * 0.000012
}
